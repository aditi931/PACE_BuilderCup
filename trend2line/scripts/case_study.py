"""Write a real-world case study from a live run, ready for slides.

    python -m scripts.case_study --trend "Dubai chocolate" --market IN
    python -m scripts.case_study --trend "Dubai chocolate" --market IN --company cadbury

Writes reports/<trend>_<market>[_<company>].md. Every number comes from the run's evidence (live Wikipedia
interest, real launch dates, Open Food Facts, researched regulations) and every source is listed. Run it with
internet access; with OFFLINE=1 the report is marked as synthetic at the top.
"""
import sys as _sys

if hasattr(_sys.stdout, "reconfigure"):
    _sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import argparse
import datetime as dt
import re

from app import pipeline
from app.config import BASE_DIR, get_settings
from app.llm import LLM
from app.mock import MOCK_HANDLERS
from app.stages import catalog
from app.stages.ingredients import taxonomy

POS = {"before_takeoff": "before take-off", "while_rising": "while rising",
       "after_peak_window_open": "after the peak, window open", "after_window_closed": "after the window closed"}


def pct(x):
    return "–" if x is None else f"{round(x * 100)}%"


def render(r: dict, args) -> str:
    mk = catalog.markets()["markets"]
    name = lambda m: mk.get(m, {}).get("name", m)  # noqa: E731
    d, dl, tr = r["decision"], r["shelf_deadline"], r["trend"]
    L = [f"# Case study: {args.trend} in {name(args.market)}", "",
         f"Run date {args.as_of} · mode **{r['mode']}** · generated by Trend2Line", ""]
    if r["mode"] == "offline":
        L += ["> **OFFLINE MODE: the interest curves in this report are synthetic. Re-run with internet access.**", ""]
    o = r.get("trend_origin")
    if o:
        L += ["## 1. Where the trend came from", "",
              f"{o['company']}'s \"{o['product']}\": {o['event']} on {o['date']} ([source]({o['source_url']})).", ""]
    W = r.get("reference_windows") or {}
    if W:
        L += ["## 2. The trend window in each market (live Wikipedia interest, own languages)", "",
              "| Market | Read from | Take-off | Peak | Window closed (<50% of peak) | Observed half-life |",
              "|---|---|---|---|---|---|"]
        for m, w in W.items():
            L.append(f"| {name(m)} | {', '.join(w['languages_used'])} | {w['takeoff_date']} | {w['peak_date']} | "
                     f"{w['window_closed_date'] or 'still open'} | "
                     f"{'–' if w['observed_half_life_days'] is None else str(w['observed_half_life_days']) + ' days'} |")
        L.append("")
    if r.get("reference_launches"):
        L += ["## 3. Real launches placed on that window", "",
              "| Date | Company · product | Market | Days after take-off | Position | Interest left | Source |",
              "|---|---|---|---|---|---|---|"]
        for x in r["reference_launches"]:
            ok = x["status"] == "ok"
            L.append(f"| {x['date']} | {x['brand']}: {x['product']} | {name(x['market'])} | "
                     f"{x['days_after_takeoff'] if ok else x['status']} | {POS.get(x.get('position'), '–')} | "
                     f"{pct(x.get('interest_at_launch_share_of_peak')) + ' of peak' if ok else '–'} | "
                     f"[{x['source_title']}]({x['source_url']}) |")
        L.append("")
    b = r.get("time_to_market_benchmark")
    L += ["## 4. Real time to market", ""]
    L += [f"Real companies needed **{b['median']} days** (median of {b['n']}; range {b['p25']}–{b['p75']}) {b['definition']}. "
          f"Fastest: {b['fastest']} ({b['fastest_days']} days).", ""] if b else \
         ["Not enough launches after take-off to measure it for this run date.", ""]
    if r.get("model_check"):
        L += ["## 5. Does the fad model match reality?", ""]
        for c in r["model_check"]:
            L.append(f"- {name(c['market'])}: predicted half-life {c['predicted_median']} days "
                     f"({c['predicted_range'][0]}–{c['predicted_range'][1]}), observed {c['observed']} days, "
                     f"{'within' if c['within_range'] else 'outside'} the predicted range"
                     f"{' (reference not yet computed)' if c['reference_status'] != 'computed' else ''}.")
        L.append("")
    L += [f"## 6. What Trend2Line says on {args.as_of} for {name(args.market)}", "",
          f"- Verdict: **{d['verdict']}**",
          f"- Interest stage: {tr['stage']} (read from {', '.join(tr['languages_used'])} Wikipedia)",
          (f"- Shelf deadline: within **{dl['go_by_days']['median']} days** (by {dl['go_by_date']['median']}) to keep "
           f"{pct(dl['go_share'])} of today's interest" if dl.get("go_by_days") else "- No deadline: interest is sustained"),
          f"- Time to shelf: {d['days_to_shelf']} days ({d['time_to_shelf_basis']})",
          f"- {'Days to spare' if (d['slack_days'] or 0) >= 0 else 'Days late'}: {abs(d['slack_days']) if d['slack_days'] is not None else '–'}",
          *(f"- Caveat: {c}" for c in d["downgrade_reasons"]), ""]
    c = r["compliance"]
    L += [f"## 7. What the label must say", "",
          f"**{name(args.market)}** ({c['regulator']}): declare {', '.join(c['allergens_to_declare']) or 'nothing'}; "
          f"rules triggered: {', '.join(c['triggered_rule_ids']) or 'none'}. "
          f"Allergen list source: [{c['allergen_list_source']['title']}]({c['allergen_list_source']['url']}) "
          f"({c['allergen_list_source']['status'].replace('_', ' ')}).", ""]
    if r.get("market_scan"):
        L += ["| Market | Must declare | Label languages to add |", "|---|---|---|"]
        for s in r["market_scan"]:
            L.append(f"| {s['name']} | {', '.join(s['mandatory_declarations']) or 'none'} | "
                     f"{', '.join(s['label_languages_needed']) or 'none'} |")
        L.append("")
    lindt = next((x for t in catalog.reference_launches().get("trends", {}).values()
                  for x in t.get("launches", []) if x.get("pack")), None)
    if lindt:
        tx = taxonomy()
        found = sorted({a for i in lindt["pack"]["ingredients"] for a in tx.resolve(i)["allergens"]})
        L += ["## 8. Validation against a real pack", "",
              f"{lindt['brand']} {lindt['product']} declares: {', '.join(lindt['pack']['declared_contains'])} "
              f"([pack data]({lindt['pack']['contains_source']})). From the printed ingredient list "
              f"([source]({lindt['pack']['ingredients_source']})), Trend2Line's allergen engine finds: "
              f"{', '.join(tx.allergen_label(a) for a in found)}.", ""]
    if args.company and r["allergen_blast_radius"]:
        L += [f"## 9. Allergen blast radius across {args.company}'s real products", "",
              "Products whose free-from claim would be at risk if this product shared their (inferred) line:", ""]
        for x in r["allergen_blast_radius"]:
            L.append(f"- {x['sku_name']}: {x['claim_label']} ({', '.join(x['allergens'])})")
        L.append("")
    L += ["## Data sources", "",
          *(f"- {p['input']}: {p['status'].replace('_', ' ')}. {p['detail']}" for p in r["provenance"]), ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--trend", required=True)
    ap.add_argument("--market", default="IN")
    ap.add_argument("--company", default="", help="profile name in data/companies/, e.g. cadbury")
    ap.add_argument("--as-of", dest="as_of", default=(dt.date.today() - dt.timedelta(days=2)).isoformat())
    args = ap.parse_args()
    s = get_settings()
    plant = None
    if args.company:
        plant = catalog.companies().get(args.company)
        if not plant:
            _sys.exit(f"No profile data/companies/{args.company}.yaml; run scripts.build_company_profile first.")
    sku = next(iter((plant or catalog.default_plant())["skus"]))
    r = pipeline.run(args.trend, sku, dt.date.fromisoformat(args.as_of), args.market, None, LLM(s, MOCK_HANDLERS),
                     s, plant=plant, scan=True)
    slug = re.sub(r"[^a-z0-9]+", "_", f"{args.trend}_{args.market}_{args.company}".lower()).strip("_")
    out = BASE_DIR / "reports" / f"{slug}.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(render(r, args), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
